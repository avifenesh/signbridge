        addPattern("what time is it", "TIME WHAT")
        addPattern("what are you doing", "YOU DO WHAT")
        addPattern("how old are you", "YOUR AGE WHAT")
        addPattern("do you understand", "YOU UNDERSTAND")
        addPattern("let's go to {PLACE}", "{PLACE} GO WE")
        addPattern("i can't {VERB}", "{VERB} I CAN'T")
        addPattern("i will {VERB}", "WILL I {VERB}")
        addPattern("see you later", "LATER SEE-YOU")
        addPattern("see you tomorrow", "TOMORROW SEE-YOU")
        addPattern("take care", "TAKE-CARE")
        addPattern("hello", "HELLO")
        addPattern("hi", "HELLO")
