        addPattern("where is the {PLACE}", "{PLACE} WHERE")
        addPattern("where is {THING}", "{THING} WHERE")
        addPattern("where is the bathroom", "BATHROOM WHERE")
        addPattern("where is the hospital", "HOSPITAL WHERE")
        addPattern("where are you from", "YOU FROM WHERE")
        addPattern("when is {EVENT}", "{EVENT} WHEN")
        addPattern("how much does {THING} cost", "{THING} COST HOW-MUCH")
