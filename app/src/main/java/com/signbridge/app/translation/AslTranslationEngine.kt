        addPattern("call an ambulance", "AMBULANCE CALL")
        addPattern("i am in pain", "PAIN I")
        addPattern("i am allergic to {THING}", "{THING} ALLERGIC I")
        addPattern("please {VERB}", "PLEASE {VERB}")
