/**
 * 3-tier ASL translation engine.
 *
 * Tier 1: Pattern hash table with template slots (instant, ~40 patterns hardcoded
 *         + full set from assets/translation/patterns.json when available)
 * Tier 2: Vector similarity via MiniLM embeddings + FAISS (fast, ~100ms)
 * Tier 3: Small fine-tuned model (T5-small ONNX) (slower, experimental)
 *
 * Falls through tiers until a confident result is found.
 * Never fails: worst case returns fingerspell-only fallback.
 *
 * Artifacts (from Python build: python -m translation.export):
 *   assets/translation/patterns.json
 *   assets/translation/faiss.index
 *   assets/translation/index_map.json
 *   assets/translation/minilm.onnx
 *   assets/translation/t5_encoder_int8.onnx (Tier 3, experimental)
 *   assets/translation/t5_decoder_int8.onnx (Tier 3, experimental)
 */
class AslTranslationEngine(private val context: Context) {

    companion object {
        private const val TAG = "AslTranslation"
        const val VECTOR_CONFIDENCE_THRESHOLD = 0.75f
        private const val PATTERNS_ASSET = "translation/patterns.json"
    }

    private val patternHash = PatternHashTable()
    private var vectorIndex: VectorSimilarityIndex? = null

    // Tier 3 — initialized when T5 ONNX checkpoint is present
    // private var t5Model: T5GlossModel? = null

    fun initialize() {
        // Tier 1: Load pattern hash table
        val loaded = patternHash.loadFromAssets(context, PATTERNS_ASSET)
        if (!loaded) {
            Log.w(TAG, "patterns.json not found in assets — using hardcoded defaults")
            patternHash.loadDefaults()
        }
        Log.i(TAG, "Tier 1: ${patternHash.patternCount} patterns")

        // Tier 2: Load pre-computed vector index
        vectorIndex = VectorSimilarityIndex(context)
        if (vectorIndex!!.load()) {
            Log.i(TAG, "Tier 2: ${vectorIndex!!.vectorCount} vectors loaded")
        } else {
            Log.w(TAG, "Tier 2: vector index not available — will skip to grammar rules")
            vectorIndex = null
        }

        // Tier 3: T5-small ONNX (not yet available)
        // t5Model = T5GlossModel(context).apply { load() }
    }

    /**
     * Translate an English sentence to ASL gloss tokens.
     * Falls through 3 tiers in order; always returns a result.
     */
    fun translate(englishSentence: String): AslTranslation? {
        val normalized = normalize(englishSentence)

        // Tier 1: Pattern hash (instant)
        val t1 = patternHash.match(normalized)
        if (t1 != null) {
            Log.d(TAG, "T1 hit: \"$normalized\" → ${t1.glossTokens}")
            return t1
        }

        // Tier 2: Vector similarity (cosine over pre-embedded patterns)
        vectorIndex?.let { idx ->
            val t2 = idx.findSimilar(normalized, VECTOR_CONFIDENCE_THRESHOLD)
            if (t2 != null) {
                Log.d(TAG, "T2 hit: \"$normalized\" → ${t2.glossTokens} (conf=${t2.confidence})")
                return t2
            }
        }

        // Tier 3: Small model (TODO: wire T5GlossModel)
        // t5Model?.let { model ->
        //     val t3 = model.generateGloss(normalized)
        //     if (t3 != null) {
        //         Log.d(TAG, "T3 hit: \"$normalized\" → ${t3.glossTokens}")
        //         return t3
        //     }
        // }

        // Fallback: rule-based ASL grammar transformation.
        // Better than word-by-word SEE: applies ASL grammar rules
        // (topic-comment, WH-questions at end, negation after verb, drop articles/copulas).
        Log.d(TAG, "Fallback (grammar rules): \"$normalized\"")
        val glossTokens = AslGrammarRules.apply(normalized)
        return AslTranslation(
            glossTokens = glossTokens,
            method = TranslationMethod.FINGERSPELL_ONLY,
            confidence = 0.4f
        )
    }

    private fun normalize(sentence: String): String {
        return sentence
            .lowercase()
            .replace(Regex("[^a-z0-9\\s']"), "")
            .replace(Regex("\\s+"), " ")
            .trim()
    }
}

/**
 * Tier 1: Pattern hash table with template slots.
 *
 * Patterns use {SLOT} notation where the slot name is a valid regex group name:
 *   "i gave {PERSON} the {OBJECT}" → "{OBJECT} I GIVE-{PERSON}"
 *
 * Runtime matching: normalize input → try each pattern regex → extract slot
 * values via named capture groups → fill ASL template.
 *
 * Primary source: assets/translation/patterns.json (generated by Agent 5 Python
 * pipeline, `python -m translation.export`).
 * Fallback: loadDefaults() minimal hardcoded set for offline / first-run.
 */
class PatternHashTable {

    data class PatternEntry(
        val pattern: Regex,
        val slotNames: List<String>,
        val aslTemplate: String,
        val sourceEnglish: String
    )

    private val patterns = mutableListOf<PatternEntry>()
    val patternCount: Int get() = patterns.size

    /**
     * Load patterns from assets/translation/patterns.json.
     * Returns true if loaded successfully, false if the asset was not found.
     *
     * JSON format (array of objects):
     *   [{"english": "i want {THING}", "asl": "{THING} I WANT", "category": "request"}, ...]
     */
    fun loadFromAssets(context: Context, assetPath: String): Boolean {
        return try {
            val stream: InputStream = context.assets.open(assetPath)
            val jsonText = stream.bufferedReader().readText()
            stream.close()

            val array = JSONArray(jsonText)
            var loaded = 0
            for (i in 0 until array.length()) {
                val obj = array.getJSONObject(i)
                val english = obj.getString("english")
                val asl = obj.getString("asl")
                addPattern(english, asl)
                loaded++
            }
            Log.i("PatternHashTable", "Loaded $loaded patterns from $assetPath")
            loaded > 0
        } catch (e: Exception) {
            Log.d("PatternHashTable", "Could not load $assetPath: ${e.message}")
            false
        }
    }

    /**
     * Minimal hardcoded pattern set — used as fallback when patterns.json is absent.
     * Keep in sync with the most common patterns from translation/tier1/patterns.py.
     */
    fun loadDefaults() {
        addPattern("i gave {PERSON} the {OBJECT}", "{OBJECT} I GIVE-{PERSON}")
